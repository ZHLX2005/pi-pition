// 场景路由：把「用户这一句话」判成一个场景 id，供 before_agent_start 决定注入哪段 SOP。
//
// 纯函数、无副作用、不读配置——配置状态属于「事实层」（role.ts 的 pition_core），
// 不该反过来影响路由（否则未绑定库时训练目标也会被判成配置场景）。
//
// 两条设计原则：
//   1. **优先级固定** setup > train > recall > log > chat —— 同句多命中时取更具体的前者
//      （「今天完成了 3 组俯卧撑」同时命中 log「今天/完成」与 train「组/俯卧撑」→ train）
//   2. **粘性**：低信息量消息（「好」「继续」「嗯」）继承上一场景 —— 一轮对话里
//      用户不会每句都重复关键词，粘性让场景跟着话题走而不是跟着关键词走
import { createRouter, isLowInfo, type SceneSignal } from "./injection/index.ts";
import type { SceneId } from "./sop.ts";

/**
 * 配置/绑定场景。两条路径命中：
 *   a) 带 pition/notion 语境的配置词（避免「帮我配置 webpack」误命中）
 *   b) 无语境但**高度专用**的动作（「换个库」「绑定库」——在日常记录语境里基本只指切库）
 */
const SETUP_RE =
  /(?:pition|notion)[^\n]{0,10}(?:配置|设置|绑定|绑|连接|换库|切库|选库|库|字段|助理模式|token|怎么用|如何用|怎么装|怎么配)|(?:配置|绑定|换库|切库|选库)[^\n]{0,8}(?:pition|notion)|(?:换|切|选|绑|连接)(?:个|一下|一)?(?:notion)?库|ntn_|助理模式/iu;

/** 锻炼场景：运动词 / 量化词（N 组·N 轮）/ 运动语境的「目标·计划」 */
const TRAIN_RE =
  /锻炼|健身|训练|运动|跑步|跑了|慢跑|快跑|散步|健走|爬山|徒步|骑行|骑车|游泳|瑜伽|打球|球类|拉伸|有氧|力量训练|俯卧撑|深蹲|平板支撑|静蹲|跳绳|引体|哑铃|卷腹|开合跳|波比|公里|配速|练(?:腰|腹|腿|背|胸|臂|肩)|第\s*[一二三四五六七八九十0-9]+\s*(?:轮|组|次)|\d+\s*(?:轮|组|次)|(?:目标|计划)[^\n]{0,8}(?:锻炼|健身|训练|运动|跑|练)|(?:锻炼|健身|训练|运动|跑|练)[^\n]{0,8}(?:目标|计划)|完成得怎么样|还差多少/;

/** 回看场景：只在显式翻旧账时命中（「昨天」单独出现不算——那可能是新记录） */
const RECALL_RE =
  /上个月|上月|上星期|上周|去年|翻旧账|历史|回顾|统计|一共|总共|哪些记录|记录了(?:什么|哪些)|之前记|以前记|昨天记|昨天写/;

/** 记录场景：时间锚定 + 生活事实词（含情绪/感悟——它们是事实事件） */
const LOG_RE =
  /记一下|记一笔|记录|记到|打卡|吃了|喝了|买了|花了|开销|花销|收入|见了|心情|开心|高兴|兴奋|难受|难过|焦虑|郁闷|烦|累|emo|悟|感悟|反思|收获|感觉|刚才|刚刚|今天|今晚|中午|早上|上午|下午|傍晚|晚上|昨天|做了|完成|收到|看了|读完/iu;

/** 低信息量消息（继承上一场景）：语气词 / 短确认 / 空白 */
const LOW_INFO_RE =
  /^(?:好|好的|好呀|好的呀|嗯|嗯嗯|哦|噢|诶|ok|okay|继续|接着|然后|是的|对|对的|可以|行|收到|谢谢|哈哈|太棒了|不错|牛|厉害|在吗|咋了|怎么了|开始|结束了?)[。.!！?？~、,，\s]*$/iu;

/** 优先级 = 数组顺序：同句多命中时取更靠前的那个 */
const SIGNALS: SceneSignal<SceneId>[] = [
  { id: "setup", re: SETUP_RE },
  { id: "train", re: TRAIN_RE },
  { id: "recall", re: RECALL_RE },
  { id: "log", re: LOG_RE },
];

/**
 * 路由到场景 id。
 *
 * 机械部分（优先级遍历 + 低信息量粘性）在 `src/injection/router.ts`；
 * 本文件只留 pition 的信号表。
 *
 * @param prompt 用户这一轮的原话（before_agent_start 的 event.prompt）
 * @param prev   上一轮场景（粘性用；首轮传 undefined）
 */
export const routeScene = createRouter<SceneId>({
  signals: SIGNALS,
  fallback: "chat",
  // 低信息量：语气词，或 ≤3 字（此时已确认不含任何场景信号）
  lowInfo: (prompt) => isLowInfo(prompt, LOW_INFO_RE),
});
